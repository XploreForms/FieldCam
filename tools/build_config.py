"""Build Field Cam's job config from the Outcomes tool (setups) and the Photo Lists tool (combos).
usage: build.py <setups dir> <combos dir> <out dir> [--new-combos]
  --new-combos : also write the photo-list documents for the confirmed outcomes (defaults for new ones)"""
import json, glob, os, re, sys
sdir, cdir, odir = sys.argv[1:4]; newc = "--new-combos" in sys.argv
os.makedirs(odir, exist_ok=True)
load = lambda f: (lambda d: d.get("data", d))(json.load(open(f)))
setups = sorted([load(f) for f in glob.glob(sdir + "/*.json")], key=lambda x: x["order"])
combos = {os.path.basename(f)[:-5]: load(f) for f in glob.glob(cdir + "/*.json")}
PK = {"Fibre (Existing Drop)":"FibreExisting","Fibre (Drop Required)":"FibreDropReq","Fibre (Drop Only)":"FibreDropOnly","Fibre":"Fibre","Fixed Wireless":"FW","Satellite":"Sat"}
slug = lambda t: re.sub(r"[^A-Za-z0-9]+", "", t)
ONAME = {"OK":"Complete","CC":"Cannot Complete","NR":"Not Required"}
def cid(s, o, r): return f'{s["work"]}_{("VAS-"+s["vas"]) if s["vas"] else PK[s["plat"]]}_{o}' + (f"-{slug(r)}" if r else "")
def old(s, o, r=None):
    k = cid(s, o, r); return combos.get(k)
def default_items(s, o, r):
    if o == "OK":
        d = old(s, "OK"); return (d["items"], d["original"], d["status"], d.get("note","")) if d else ([], [], "todo", "")
    if o == "CC":
        it = [{"name":"House (customer no-show)","req":True,"los":False}] if r and "no show" in r.lower() else []
        return it, it, "todo", ""
    if o == "NR":
        src = None
        if s["plat"] == "Fixed Wireless" and r == "No Serviceable Signal": src = old(s, "NR", "NLOS")
        if s["plat"] == "Satellite" and r == "NLOS": src = old(s, "NR", "Satellite NLOS")
        it = src["items"] if src else []
        return it, it, "todo", ""
    return [], [], "todo", ""
SETUP, PHOTOS, docs, order = {}, {}, [], 0
for s in setups:
    pl = f'VAS · {s["vas"]}' if s["vas"] else s["plat"]
    SETUP.setdefault(s["work"], {})[pl] = {o: {"on": bool(s["outcomes"][o]["on"]), "reasons": s["outcomes"][o]["reasons"]} for o in ("OK","CC","NR")}
    for o in ("OK","CC","NR"):
        oc = s["outcomes"][o]
        if not oc["on"]: continue
        for r in (oc["reasons"] or [None]):
            k = cid(s, o, r)
            if not newc and k in combos: d = combos[k]; items = d["items"]
            else:
                items, orig, st, note = default_items(s, o, r)
                d = {"order":order, "work":s["work"], "workName":s["workName"], "plat":s["plat"], "vas":s["vas"], "platLabel":pl,
                     "outcome":o, "outcomeName":ONAME[o], "reason":r, "items":items, "original":orig, "status":st, "note":note, "updatedAt":None}
                docs.append((k, d))
            order += 1
            PHOTOS[f'{s["work"]}|{pl}|{o}|{r or ""}'] = [[i["name"], 1 if i["req"] else 0, 1 if i["los"] else 0] for i in items if i["name"].strip()]
js = ("/*CONFIG:BEGIN — generated by build.py from the Field Cam Outcomes and Photo Lists tools; regenerate, don't hand-edit */\n"
      "const SETUP = " + json.dumps(SETUP, ensure_ascii=False, separators=(",", ":")) + ";\n"
      "const PHOTOS = " + json.dumps(PHOTOS, ensure_ascii=False, separators=(",", ":")).replace('],"', '],\n"') + ";\n/*CONFIG:END*/")
open(odir + "/config.js", "w").write(js)
if newc:
    os.makedirs(odir + "/docs", exist_ok=True)
    for k, d in docs: json.dump(d, open(f"{odir}/docs/{k}.json", "w"))
    newids = {k for k, _ in docs}
    dels = [{"op":"delete","collection":"combos","doc_id":k} for k in combos if k not in newids]
    sets = [{"op":"set","collection":"combos","doc_id":k,"file_path":f"{odir}/docs/{k}.json"} for k, _ in docs]
    json.dump(dels, open(odir + "/dels.json", "w")); json.dump(sets, open(odir + "/sets.json", "w"))
    print("photo combos:", len(docs), "| delete:", len(dels))
print("platform setups:", len(setups), "| photo lists:", len(PHOTOS))
